package com.gods.saas.service.impl;

import com.gods.saas.domain.model.*;
import com.gods.saas.domain.repository.*;
import com.gods.saas.service.impl.impl.NotificationService;
import org.junit.jupiter.api.*;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.*;
import org.springframework.transaction.support.TransactionTemplate;
import org.springframework.security.core.Authentication;
import java.util.*;
import java.util.concurrent.*;
import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.*;
import static org.mockito.Mockito.*;

/** Exercise the shared redemption transaction with actual concurrent database row locks. */
class RewardRedemptionConcurrencyTest {
    JdbcTemplate jdbc;TransactionTemplate tx;ClientRewardService service;
    NotificationService notices;
    @BeforeEach void setup() {
        var data=new DriverManagerDataSource("jdbc:h2:mem:"+UUID.randomUUID()+";MODE=PostgreSQL;DB_CLOSE_DELAY=-1;LOCK_TIMEOUT=4000","sa","");
        jdbc=new JdbcTemplate(data);tx=new TransactionTemplate(new DataSourceTransactionManager(data));
        jdbc.execute("create table balance(customer_id bigint primary key, points int)");
        jdbc.execute("create table prize(id bigint primary key, points int, stock int)");
        jdbc.execute("create table redemption(id bigint generated by default as identity, customer_id bigint)");
        jdbc.update("insert into balance values(7,100),(8,100)");jdbc.update("insert into prize values(3,60,null)");
        var customers=mock(CustomerRepository.class);var accounts=mock(LoyaltyAccountRepository.class);
        var rewards=mock(RewardItemRepository.class);var redemptions=mock(RewardRedemptionRepository.class);
        notices=mock(NotificationService.class);
        for(long id:List.of(7L,8L)) {
            var customer=Customer.builder().id(id).tenant(new Tenant(2L)).phoneVerified(true).whatsappTransactionalEnabled(true).build();
            when(customers.findById(id)).thenReturn(Optional.of(customer));
            when(customers.findByIdAndTenantIdWithTenant(id,2L)).thenReturn(Optional.of(customer));
        }
        when(accounts.findForRedemption(eq(2L),anyLong())).thenAnswer(i->{Long id=i.getArgument(1);int points=jdbc.queryForObject("select points from balance where customer_id=? for update",Integer.class,id);
            return Optional.of(LoyaltyAccount.builder().id(id).puntosDisponibles(points).build());});
        when(rewards.findForRedemption(3L,2L)).thenAnswer(i->{var row=jdbc.queryForMap("select * from prize where id=3 for update");
            return Optional.of(RewardItem.builder().id(3L).nombre("Premio").puntosRequeridos((Integer)row.get("points")).stock((Integer)row.get("stock")).build());});
        when(accounts.save(any())).thenAnswer(i->{LoyaltyAccount account=i.getArgument(0);jdbc.update("update balance set points=? where customer_id=?",account.getPuntosDisponibles(),account.getId());return account;});
        when(rewards.save(any())).thenAnswer(i->{RewardItem reward=i.getArgument(0);jdbc.update("update prize set stock=? where id=3",reward.getStock());return reward;});
        when(redemptions.save(any())).thenAnswer(i->{RewardRedemption item=i.getArgument(0);jdbc.update("insert into redemption(customer_id) values(?)",item.getCustomerId());item.setId(1L);return item;});
        service=new ClientRewardService(customers,accounts,rewards,redemptions,mock(LoyaltyMovementRepository.class),mock(LoyaltyLotConsumptionService.class),notices);
    }
    @AfterEach void cleanup() {jdbc.execute("shutdown");}
    boolean redeem(boolean whatsapp,long customer) {
        try {tx.execute(status->{
            if(whatsapp) return service.redeemForWhatsapp(2L,customer,3L,60);
            Authentication auth=mock(Authentication.class);when(auth.getName()).thenReturn(Long.toString(customer));return service.redeemReward(auth,3L);
        });return true;} catch(ClientRewardService.RewardUnavailableException expected) {return false;}
    }
    int race(long appCustomer) throws Exception {
        var pool=Executors.newFixedThreadPool(2);var gate=new CountDownLatch(1);
        try {
            var one=pool.submit(()->{gate.await();return redeem(true,7L);});
            var two=pool.submit(()->{gate.await();return redeem(false,appCustomer);});gate.countDown();
            return (one.get(8,TimeUnit.SECONDS)?1:0)+(two.get(8,TimeUnit.SECONDS)?1:0);
        } finally {pool.shutdownNow();}
    }
    @Test void simultaneousAppAndWhatsappCanSpendBalanceOnlyOnce() throws Exception {
        assertEquals(1,race(7L));assertEquals(40,jdbc.queryForObject("select points from balance where customer_id=7",Integer.class));
        assertEquals(1,jdbc.queryForObject("select count(*) from redemption",Integer.class));
    }
    @Test void twoCustomersCannotBothTakeLastStockAcrossChannels() throws Exception {
        jdbc.update("update prize set stock=1 where id=3");assertEquals(1,race(8L));
        assertEquals(0,jdbc.queryForObject("select stock from prize where id=3",Integer.class));
        assertEquals(140,jdbc.queryForObject("select sum(points) from balance",Integer.class));
    }
    @Test void unexpectedFailureRollsBackBalanceStockAndGeneratedCode() {
        jdbc.update("update prize set stock=1 where id=3");
        doThrow(new IllegalStateException("notification failed")).when(notices).notifyRewardRedeemed(any(),any(),any());
        assertThrows(IllegalStateException.class,()->redeem(true,7L));
        assertEquals(100,jdbc.queryForObject("select points from balance where customer_id=7",Integer.class));
        assertEquals(1,jdbc.queryForObject("select stock from prize where id=3",Integer.class));
        assertEquals(0,jdbc.queryForObject("select count(*) from redemption",Integer.class));
    }
}
